defmodule ClaudiverseServerWeb.Endpoint do
  use Phoenix.Endpoint, otp_app: :claudiverse_server

  # The session will be stored in the cookie and signed,
  # this means its contents can be read but not tampered with.
  # Set :encryption_salt if you would also like to encrypt it.
  @session_options [
    store: :cookie,
    key: "_claudiverse_server_key",
    signing_salt: "//Tp6YQi",
    same_site: "Lax"
  ]

  socket "/socket", ClaudiverseServerWeb.UserSocket,
    websocket: [connect_info: [:peer_data, session: @session_options]],
    longpoll: false

  # Serve at "/" the static files from "priv/static" directory.
  #
  # When code reloading is disabled (e.g., in production),
  # the `gzip` option is enabled to serve compressed
  # static files generated by running `phx.digest`.
  plug Plug.Static,
    at: "/",
    from: :claudiverse_server,
    gzip: not code_reloading?,
    only: ClaudiverseServerWeb.static_paths()

  # Code reloading can be explicitly enabled under the
  # :code_reloader configuration of your endpoint.
  if code_reloading? do
    plug Phoenix.CodeReloader
    plug Phoenix.Ecto.CheckRepoStatus, otp_app: :claudiverse_server
  end

  plug Plug.RequestId
  plug Plug.Telemetry, event_prefix: [:phoenix, :endpoint]

  # The API proxy must see the raw request body, so it sits before the parsers.
  # It halts every /proxy request and passes everything else through.
  plug ClaudiverseServerWeb.ProxyPlug

  plug Plug.Parsers,
    # Multipart is raised past Plug's 8 MB default to admit the largest upload
    # (an app build, AppBuilds.max_bytes()) plus its multipart framing; each
    # store enforces its own exact cap (SeatFiles 25 MiB, AppBuilds 100 MiB).
    # Uploads are spooled to a temp file, not held in memory.
    parsers: [:urlencoded, {:multipart, length: ClaudiverseServer.AppBuilds.max_bytes() + 1_000_000}, :json],
    pass: ["*/*"],
    json_decoder: Phoenix.json_library()

  plug Plug.MethodOverride
  plug Plug.Head
  plug Plug.Session, @session_options
  plug Corsica, origins: "*", allow_headers: ["content-type", "authorization"]
  plug ClaudiverseServerWeb.Router
end
